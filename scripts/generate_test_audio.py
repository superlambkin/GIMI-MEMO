# ─── 音声生成 ──────────────────────────────────────────────

def generate_audio(text: str, filename: str, lang: str = "ja", slow: bool = False):
    """gTTS で音声を生成して MP3 として保存。"""
    filepath = os.path.join(OUTPUT_DIR, filename)
    if HAS_GTTS:
        print(f"Generating {filename}...")
        tts = gTTS(text=text, lang=lang, slow=slow)
        tts.save(filepath)
        file_size = os.path.getsize(filepath)
        print(f"  Saved: {filepath} ({file_size} bytes)")
    else:
        print(f"  [SKIP] gTTS not available, skipping {filename}")
        # プレースホルダーファイルを作成（実際のテスト用）
        with open(filepath, 'w') as f:
            f.write(f"PLACEHOLDER: {filename} - Install gTTS to generate actual audio")
        print(f"  Created placeholder: {filepath}")
    return filepath


